/// Typed RSA-PSS parameters (from `CK_RSA_PKCS_PSS_PARAMS`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PssParams {
    /// Message hash.
    pub hash: HashAlg,
    /// Salt length in bytes (always equal to the hash length; see
    /// [`PssParams::from_ck`]).
    pub salt_len: usize,
}

impl PssParams {
    /// Validate the fields of a `CK_RSA_PKCS_PSS_PARAMS`.
    ///
    /// Both backends implement PSS with MGF1 using the message hash and a salt
    /// length equal to the hash length (the FIPS 186-5 recommended
    /// configuration). Anything else is rejected instead of being silently
    /// replaced (H2-21).
    pub fn from_ck(hash_alg: CK_ULONG, mgf: CK_ULONG, s_len: CK_ULONG) -> HsmResult<Self> {
        let hash = match hash_alg {
            CKM_SHA256 => HashAlg::Sha256,
            CKM_SHA384 => HashAlg::Sha384,
            CKM_SHA512 => HashAlg::Sha512,
            _ => return Err(HsmError::MechanismParamInvalid),
        };
        let expected_mgf = match hash {
            HashAlg::Sha256 => CKG_MGF1_SHA256,
            HashAlg::Sha384 => CKG_MGF1_SHA384,
            HashAlg::Sha512 => CKG_MGF1_SHA512,
        };
        if mgf != expected_mgf || s_len as usize != hash.output_len() {
            tracing::error!("RSA-PSS: unsupported MGF or salt length");
            return Err(HsmError::MechanismParamInvalid);
        }
        Ok(Self {
            hash,
            salt_len: hash.output_len(),
        })
    }

    /// Check that explicit parameters supplied with a hash-specific PSS
    /// mechanism (`CKM_SHAx_RSA_PKCS_PSS`) are consistent with it.
    pub fn check_consistent_with(&self, mechanism: CK_MECHANISM_TYPE) -> HsmResult<()> {
        let mech_hash = crate::crypto::sign::pss_mechanism_to_hash(mechanism)?;
        if mech_hash != self.hash {
            return Err(HsmError::MechanismParamInvalid);
        }
        Ok(())
    }
}

