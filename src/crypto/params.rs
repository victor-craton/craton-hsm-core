//! Typed mechanism parameters passed from the PKCS#11 ABI layer into the
//! crypto layer (H2-22, H1-16, A2-09/A2-12).
//!
//! The ABI layer parses the standard `CK_*_PARAMS` structures (dereferencing
//! any embedded pointers while they are still valid, i.e. during `*Init`) and
//! stores a *canonical, pointer-free encoding* produced by [`GcmParams::encode`],
//! [`OaepParams::encode`] or [`CtrParams::encode`] in the session's active
//! operation. The crypto layer decodes that encoding when the operation runs.
//! The encodings start with a magic byte and version so that raw legacy bytes
//! can never be mistaken for a canonical encoding.

use zeroize::Zeroize;

use crate::crypto::sign::{HashAlg, OaepHash};
use crate::error::{HsmError, HsmResult};
use crate::pkcs11_abi::constants::*;
use crate::pkcs11_abi::types::{CK_MECHANISM_TYPE, CK_ULONG};

// PKCS#11 constants used by the parameter parsers now live in
// `pkcs11_abi::constants`; re-exported here for existing callers.
pub use crate::pkcs11_abi::constants::{
    CKD_NULL, CKD_SHA1_KDF, CKD_SHA224_KDF, CKD_SHA256_KDF, CKD_SHA384_KDF, CKD_SHA512_KDF,
    CKG_MGF1_SHA1, CKG_MGF1_SHA224, CKG_MGF1_SHA256, CKG_MGF1_SHA384, CKG_MGF1_SHA512,
    CKR_CURVE_NOT_SUPPORTED, CKR_DOMAIN_PARAMS_INVALID, CKZ_DATA_SPECIFIED,
};

// ============================================================================
// AES-GCM
// ============================================================================

/// Only 96-bit IVs are supported (SP 800-38D §5.2.1.1 recommendation; the
/// only length usable with the IG C.H IV-generation constructions).
pub const GCM_IV_LEN: usize = 12;
/// Upper bound on the AAD accepted for a single operation.
pub const GCM_MAX_AAD_LEN: usize = 16 * 1024 * 1024;
/// Permitted authentication tag lengths in bits (SP 800-38D §5.2.1.2).
/// 32- and 64-bit tags are deliberately not supported.
pub const GCM_ALLOWED_TAG_BITS: [u32; 5] = [96, 104, 112, 120, 128];

const GCM_MAGIC: u8 = b'G';
const CTR_MAGIC: u8 = b'C';
const OAEP_MAGIC: u8 = b'O';
const PARAM_VERSION: u8 = 1;

/// Typed AES-GCM parameters (from `CK_GCM_PARAMS`).
#[derive(Clone, PartialEq, Eq)]
pub struct GcmParams {
    /// 96-bit IV. Either supplied by the caller or generated by the module.
    pub iv: [u8; GCM_IV_LEN],
    /// Additional authenticated data.
    pub aad: Vec<u8>,
    /// Authentication tag length in bits.
    pub tag_bits: u32,
    /// `true` when the IV was generated inside the module by the approved
    /// DRBG (SP 800-38D §8.2.2 / FIPS 140-3 IG C.H scenario 2).
    pub iv_generated: bool,
    /// `true` for the deprecated vendor framing used when the caller passes
    /// no `CK_GCM_PARAMS` at all: the module generates the IV, the output is
    /// `IV || ciphertext || tag` and decryption expects the same framing.
    pub legacy_framing: bool,
}

impl std::fmt::Debug for GcmParams {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("GcmParams")
            .field("aad_len", &self.aad.len())
            .field("tag_bits", &self.tag_bits)
            .field("iv_generated", &self.iv_generated)
            .field("legacy_framing", &self.legacy_framing)
            .finish()
    }
}

impl GcmParams {
    /// Build and validate GCM parameters from the values of a `CK_GCM_PARAMS`.
    ///
    /// Rejects IVs that are not 96 bits, oversized AAD and tag lengths outside
    /// [`GCM_ALLOWED_TAG_BITS`] with `MechanismParamInvalid`.
    pub fn new(iv: &[u8], aad: &[u8], tag_bits: CK_ULONG, iv_generated: bool) -> HsmResult<Self> {
        if iv.len() != GCM_IV_LEN {
            tracing::error!(
                "AES-GCM: IV length {} not supported (only 96-bit IVs)",
                iv.len()
            );
            return Err(HsmError::MechanismParamInvalid);
        }
        if aad.len() > GCM_MAX_AAD_LEN {
            return Err(HsmError::MechanismParamInvalid);
        }
        let tag_bits = u32::try_from(tag_bits).map_err(|_| HsmError::MechanismParamInvalid)?;
        if !GCM_ALLOWED_TAG_BITS.contains(&tag_bits) {
            tracing::error!("AES-GCM: tag length {} bits not permitted", tag_bits);
            return Err(HsmError::MechanismParamInvalid);
        }
        let mut iv_arr = [0u8; GCM_IV_LEN];
        iv_arr.copy_from_slice(iv);
        Ok(Self {
            iv: iv_arr,
            aad: aad.to_vec(),
            tag_bits,
            iv_generated,
            legacy_framing: false,
        })
    }

    /// Parameters for the deprecated "no `CK_GCM_PARAMS`" framing.
    /// The IV is generated per operation by the module.
    pub fn legacy(generated_iv: [u8; GCM_IV_LEN]) -> Self {
        Self {
            iv: generated_iv,
            aad: Vec::new(),
            tag_bits: 128,
            iv_generated: true,
            legacy_framing: true,
        }
    }

    /// Tag length in bytes.
    pub fn tag_len(&self) -> usize {
        (self.tag_bits / 8) as usize
    }

    /// Canonical pointer-free encoding stored in the session operation.
    pub fn encode(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(5 + GCM_IV_LEN + self.aad.len());
        out.push(GCM_MAGIC);
        out.push(PARAM_VERSION);
        out.push(u8::from(self.iv_generated) | (u8::from(self.legacy_framing) << 1));
        out.push(self.tag_bits as u8);
        out.extend_from_slice(&self.iv);
        out.extend_from_slice(&self.aad);
        out
    }

    /// Decode a value produced by [`GcmParams::encode`].
    pub fn decode(bytes: &[u8]) -> HsmResult<Self> {
        if bytes.len() < 4 + GCM_IV_LEN || bytes[0] != GCM_MAGIC || bytes[1] != PARAM_VERSION {
            return Err(HsmError::MechanismParamInvalid);
        }
        let flags = bytes[2];
        let tag_bits = u32::from(bytes[3]);
        let mut p = Self::new(
            &bytes[4..4 + GCM_IV_LEN],
            &bytes[4 + GCM_IV_LEN..],
            tag_bits as CK_ULONG,
            flags & 1 != 0,
        )?;
        p.legacy_framing = flags & 2 != 0;
        Ok(p)
    }

    /// True when `bytes` is a canonical GCM encoding.
    pub fn is_encoded(bytes: &[u8]) -> bool {
        bytes.len() >= 4 + GCM_IV_LEN && bytes[0] == GCM_MAGIC && bytes[1] == PARAM_VERSION
    }
}

