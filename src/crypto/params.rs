/// Key derivation function for `CKM_ECDH1_DERIVE` (`CK_EC_KDF_TYPE`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EcdhKdf {
    /// `CKD_NULL`: the leftmost bytes of the shared secret Z are the key.
    /// Not an approved key-derivation method (IG D.F); refused in FIPS mode.
    Null,
    /// ANSI X9.63 / SP 800-56C one-step KDF with SHA-224.
    Sha224,
    /// ANSI X9.63 / SP 800-56C one-step KDF with SHA-256.
    Sha256,
    /// ANSI X9.63 / SP 800-56C one-step KDF with SHA-384.
    Sha384,
    /// ANSI X9.63 / SP 800-56C one-step KDF with SHA-512.
    Sha512,
}

impl EcdhKdf {
    /// Map a `CK_EC_KDF_TYPE`.
    pub fn from_ck(kdf: CK_ULONG) -> HsmResult<Self> {
        match kdf {
            CKD_NULL => Ok(Self::Null),
            CKD_SHA224_KDF => Ok(Self::Sha224),
            CKD_SHA256_KDF => Ok(Self::Sha256),
            CKD_SHA384_KDF => Ok(Self::Sha384),
            CKD_SHA512_KDF => Ok(Self::Sha512),
            // CKD_SHA1_KDF and the SP 800-108 / SHA-3 KDFs are not implemented.
            _ => Err(HsmError::MechanismParamInvalid),
        }
    }
}

/// Typed ECDH parameters (from `CK_ECDH1_DERIVE_PARAMS`).
#[derive(Clone, PartialEq, Eq)]
pub struct EcdhParams {
    /// Key derivation function.
    pub kdf: EcdhKdf,
    /// `pSharedData` — used as the KDF `SharedInfo`/`OtherInfo`.
    pub shared_data: Vec<u8>,
    /// `pPublicData` — the peer's public point (SEC1, compressed or
    /// uncompressed; raw X9.62 or DER OCTET STRING wrapped).
    pub public_data: Vec<u8>,
}

impl std::fmt::Debug for EcdhParams {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("EcdhParams")
            .field("kdf", &self.kdf)
            .field("shared_data_len", &self.shared_data.len())
            .field("public_data_len", &self.public_data.len())
            .finish()
    }
}

impl EcdhParams {
    /// Build from the fields of a `CK_ECDH1_DERIVE_PARAMS`.
    pub fn from_ck(kdf: CK_ULONG, shared_data: &[u8], public_data: &[u8]) -> HsmResult<Self> {
        let kdf = EcdhKdf::from_ck(kdf)?;
        if kdf == EcdhKdf::Null && !shared_data.is_empty() {
            // PKCS#11: with CKD_NULL pSharedData must be NULL.
            return Err(HsmError::MechanismParamInvalid);
        }
        if public_data.is_empty() {
            return Err(HsmError::MechanismParamInvalid);
        }
        Ok(Self {
            kdf,
            shared_data: shared_data.to_vec(),
            public_data: public_data.to_vec(),
        })
    }

    /// Backward-compatible form: the mechanism parameter is the raw peer
    /// public point. Uses the standard X9.63 SHA-256 KDF with no shared data
    /// (so both parties derive the same key; H2-06).
    pub fn from_legacy_point(point: &[u8]) -> HsmResult<Self> {
        if point.is_empty() {
            return Err(HsmError::MechanismParamInvalid);
        }
        Ok(Self {
            kdf: EcdhKdf::Sha256,
            shared_data: Vec::new(),
            public_data: point.to_vec(),
        })
    }
}

/// If `data` is a DER OCTET STRING, return its contents.
///
/// PKCS#11 v2.40 permits `pPublicData`/`CKA_EC_POINT` either as a raw X9.62
/// point or DER-wrapped in an OCTET STRING. Because an uncompressed point also
/// starts with `0x04`, callers must first try `data` as a raw point and only
/// fall back to the inner value if that fails.
pub fn der_octet_string_inner(data: &[u8]) -> Option<&[u8]> {
    if data.len() < 2 || data[0] != 0x04 {
        return None;
    }
    let (len, hdr) = match data[1] {
        l if l < 0x80 => (l as usize, 2),
        0x81 if data.len() >= 3 => (data[2] as usize, 3),
        _ => return None,
    };
    if data.len() == hdr + len {
        Some(&data[hdr..])
    } else {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gcm_roundtrip_and_validation() {
        let p = GcmParams::new(&[7u8; 12], b"aad", 96, false).unwrap();
        let d = GcmParams::decode(&p.encode()).unwrap();
        assert_eq!(p, d);
        assert_eq!(d.tag_len(), 12);
        assert!(GcmParams::new(&[0u8; 16], b"", 128, false).is_err());
        assert!(GcmParams::new(&[0u8; 12], b"", 64, false).is_err());
        assert!(GcmParams::new(&[0u8; 12], b"", 127, false).is_err());
        let l = GcmParams::legacy([1u8; 12]);
        assert!(GcmParams::decode(&l.encode()).unwrap().legacy_framing);
    }

    #[test]
    fn ctr_blocks_available() {
        let mut cb = [0u8; 16];
        cb[15] = 0xFE;
        let p = CtrParams::new(8, &cb).unwrap();
        assert_eq!(p.blocks_available(), 2);
        let p = CtrParams::decode(&p.encode()).unwrap();
        assert_eq!(p.counter_bits, 8);
        assert!(CtrParams::new(0, &cb).is_err());
        assert!(CtrParams::new(129, &cb).is_err());
    }

    #[test]
    fn oaep_params_validation() {
        assert!(OaepParams::from_ck(CKM_SHA256, CKG_MGF1_SHA256, CKZ_DATA_SPECIFIED, b"l").is_ok());
        assert!(OaepParams::from_ck(CKM_SHA256, CKG_MGF1_SHA384, 0, b"").is_err());
        assert!(OaepParams::from_ck(CKM_SHA_1, CKG_MGF1_SHA1, 0, b"").is_err());
        let p = OaepParams::from_ck(CKM_SHA384, CKG_MGF1_SHA384, CKZ_DATA_SPECIFIED, b"x").unwrap();
        assert_eq!(OaepParams::decode(&p.encode()).unwrap(), p);
    }

    #[test]
    fn pss_params_validation() {
        assert!(PssParams::from_ck(CKM_SHA256, CKG_MGF1_SHA256, 32).is_ok());
        assert!(PssParams::from_ck(CKM_SHA256, CKG_MGF1_SHA256, 20).is_err());
        assert!(PssParams::from_ck(CKM_SHA256, CKG_MGF1_SHA512, 32).is_err());
    }

    #[test]
    fn der_octet_string_unwrapping() {
        let mut point = vec![0x04u8];
        point.extend_from_slice(&[0xAA; 64]);
        assert_eq!(der_octet_string_inner(&point), None);
        let mut wrapped = vec![0x04, 65];
        wrapped.extend_from_slice(&point);
        assert_eq!(der_octet_string_inner(&wrapped), Some(&point[..]));
    }
}
