/// Typed AES-CTR parameters (from `CK_AES_CTR_PARAMS`).
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct CtrParams {
    /// Number of low-order bits of the counter block that form the counter
    /// (`ulCounterBits`, 1..=128).
    pub counter_bits: u32,
    /// Initial counter block (`cb`).
    pub cb: [u8; 16],
}

impl std::fmt::Debug for CtrParams {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("CtrParams")
            .field("counter_bits", &self.counter_bits)
            .finish()
    }
}

impl CtrParams {
    /// Build and validate CTR parameters.
    pub fn new(counter_bits: CK_ULONG, cb: &[u8]) -> HsmResult<Self> {
        if counter_bits == 0 || counter_bits > 128 || cb.len() != 16 {
            return Err(HsmError::MechanismParamInvalid);
        }
        let mut arr = [0u8; 16];
        arr.copy_from_slice(cb);
        Ok(Self {
            counter_bits: counter_bits as u32,
            cb: arr,
        })
    }

    /// Legacy encoding: a raw 16-byte counter block with a full 128-bit counter.
    pub fn from_legacy_iv(iv: &[u8]) -> HsmResult<Self> {
        Self::new(128, iv)
    }

    /// Number of counter blocks still available from `cb` before the
    /// `counter_bits`-wide counter field would wrap.
    pub fn blocks_available(&self) -> u128 {
        let cb = u128::from_be_bytes(self.cb);
        if self.counter_bits >= 128 {
            // The full block is the counter; wrapping the 128-bit block is
            // treated as an overflow.
            u128::MAX - cb
        } else {
            let mask = (1u128 << self.counter_bits) - 1;
            mask - (cb & mask) + 1
        }
    }

    /// Canonical encoding.
    pub fn encode(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(3 + 16);
        out.push(CTR_MAGIC);
        out.push(PARAM_VERSION);
        out.push(self.counter_bits as u8);
        out.extend_from_slice(&self.cb);
        out
    }

    /// Decode a canonical encoding, or (for backward compatibility) a raw
    /// 16-byte counter block.
    pub fn decode(bytes: &[u8]) -> HsmResult<Self> {
        if bytes.len() == 16 {
            return Self::from_legacy_iv(bytes);
        }
        if bytes.len() != 19 || bytes[0] != CTR_MAGIC || bytes[1] != PARAM_VERSION {
            return Err(HsmError::MechanismParamInvalid);
        }
        let bits = bytes[2] as CK_ULONG;
        // 128 does not fit in the stored byte when encoded as 0x80? It does
        // (0x80 == 128), so no special case is needed.
        Self::new(bits, &bytes[3..19])
    }
}

