/// Typed RSA-OAEP parameters (from `CK_RSA_PKCS_OAEP_PARAMS`).
#[derive(Clone, PartialEq, Eq)]
pub struct OaepParams {
    /// Hash used for the label hash and (identically) for MGF1.
    pub hash: OaepHash,
    /// Encoding parameter (label). Empty when none was supplied.
    pub label: Vec<u8>,
}

impl std::fmt::Debug for OaepParams {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("OaepParams")
            .field("hash", &self.hash)
            .field("label_len", &self.label.len())
            .finish()
    }
}

impl Drop for OaepParams {
    fn drop(&mut self) {
        self.label.zeroize();
    }
}

/// Maximum OAEP label length accepted.
pub const OAEP_MAX_LABEL_LEN: usize = 64 * 1024;

impl OaepParams {
    /// Parameters with an empty label.
    pub fn new(hash: OaepHash) -> Self {
        Self {
            hash,
            label: Vec::new(),
        }
    }

    /// Validate the fields of a `CK_RSA_PKCS_OAEP_PARAMS`.
    ///
    /// * `hashAlg` must be SHA-256/384/512 (SHA-1 is rejected).
    /// * `mgf` must be MGF1 with the **same** hash (both backends only
    ///   implement matching hashes; mismatches are rejected rather than
    ///   silently ignored — H1-16/H2-21).
    /// * `source` must be `CKZ_DATA_SPECIFIED` when a label is present
    ///   (0 is tolerated for an empty label).
    pub fn from_ck(
        hash_alg: CK_ULONG,
        mgf: CK_ULONG,
        source: CK_ULONG,
        label: &[u8],
    ) -> HsmResult<Self> {
        let hash = match hash_alg {
            CKM_SHA256 => OaepHash::Sha256,
            CKM_SHA384 => OaepHash::Sha384,
            CKM_SHA512 => OaepHash::Sha512,
            CKM_SHA_1 => {
                tracing::error!("RSA-OAEP with SHA-1 is rejected — use SHA-256 or stronger");
                return Err(HsmError::MechanismParamInvalid);
            }
            _ => return Err(HsmError::MechanismParamInvalid),
        };
        let expected_mgf = match hash {
            OaepHash::Sha256 => CKG_MGF1_SHA256,
            OaepHash::Sha384 => CKG_MGF1_SHA384,
            OaepHash::Sha512 => CKG_MGF1_SHA512,
        };
        if mgf != expected_mgf {
            tracing::error!("RSA-OAEP: MGF1 hash must match hashAlg");
            return Err(HsmError::MechanismParamInvalid);
        }
        if !label.is_empty() && source != CKZ_DATA_SPECIFIED {
            return Err(HsmError::MechanismParamInvalid);
        }
        if source != 0 && source != CKZ_DATA_SPECIFIED {
            return Err(HsmError::MechanismParamInvalid);
        }
        if label.len() > OAEP_MAX_LABEL_LEN {
            return Err(HsmError::MechanismParamInvalid);
        }
        Ok(Self {
            hash,
            label: label.to_vec(),
        })
    }

    /// Canonical encoding.
    pub fn encode(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(3 + self.label.len());
        out.push(OAEP_MAGIC);
        out.push(PARAM_VERSION);
        out.push(match self.hash {
            OaepHash::Sha256 => 1,
            OaepHash::Sha384 => 2,
            OaepHash::Sha512 => 3,
        });
        out.extend_from_slice(&self.label);
        out
    }

    /// Decode a canonical encoding.
    pub fn decode(bytes: &[u8]) -> HsmResult<Self> {
        if bytes.len() < 3 || bytes[0] != OAEP_MAGIC || bytes[1] != PARAM_VERSION {
            return Err(HsmError::MechanismParamInvalid);
        }
        let hash = match bytes[2] {
            1 => OaepHash::Sha256,
            2 => OaepHash::Sha384,
            3 => OaepHash::Sha512,
            _ => return Err(HsmError::MechanismParamInvalid),
        };
        Ok(Self {
            hash,
            label: bytes[3..].to_vec(),
        })
    }
}

